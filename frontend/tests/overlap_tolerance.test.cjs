const assert = require('node:assert/strict')
const { test } = require('node:test')
const path = require('node:path')
const fs = require('node:fs')
const log = (start, end) => ({ from_time: '2026-10-02 '+start, to_time: '2026-10-02 '+end })
test('weekly UI uses total union overlap and exact five-minute boundary', async () => {
  const { overlapMilliseconds: overlap, MAX_OVERLAP_MS: limit } = await import('../src/utils/timeOverlap.js')
  assert.equal(overlap(log('09:00:00','10:00:00'), [log('09:55:00','10:30:00')]), limit)
  assert.equal(overlap(log('09:00:00','10:00:00'), [log('09:54:59','10:30:00')]), limit+1000)
  assert.equal(overlap(log('09:00:00','09:14:00'), [log('09:00:00','09:04:00'),log('09:10:00','09:14:00')]), 480000)
  assert.equal(overlap(log('09:00:00','09:10:00'), [log('09:00:00','09:04:00'),log('09:02:00','09:05:00')]), limit)
  assert.equal(overlap(log('09:00:00','10:00:37'), [log('10:00:00','10:30:00')]), 37000)
  assert.equal(overlap(log('09:00:00','10:00:00'), [log('10:00:00','10:30:00')]), 0)
})
test('table warning/highlighting and manual add/edit use the weekly allowance', () => {
  const source = fs.readFileSync(path.join(__dirname, '../src/components/TimeLogsTable.vue'), 'utf8')
  assert.match(source, /const blocked = logs\.map.*overlapMilliseconds/)
  assert.match(source, /isWeekly\.value && prospective\.some/)
  assert.match(source, /const clash = !isWeekly\.value/)
})
